const now = new Date();
const isoDaysAgo = (days: number, hours = 0) => {
  const d = new Date(now.getTime() - days * 86400000 - hours * 3600000);
  return d.toISOString();
};

const isoDaysAhead = (days: number, hours = 0) => {
  const d = new Date(now.getTime() + days * 86400000 + hours * 3600000);
  return d.toISOString();
};

